#!/usr/bin/env python3
"""Generate assets/styles-dark.css from assets/styles.css.

Every declaration of styles.css that contains a colour is repeated under
html[data-theme="dark"] with the colour transformed: the lightness is inverted
and compressed into [0.10, 0.92]; hue and alpha are kept, and the saturation of
colours that become dark is reduced. Shadows and the dialog backdrop keep their
original colours, so they stay dark.
Run after changing colours in styles.css: python scripts/build_dark_theme.py
"""
from __future__ import annotations
import argparse
import colorsys
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SCOPE = 'html[data-theme="dark"]'
# Colour keywords only as whole values, never inside identifiers such as var(--white).
COLOR = re.compile(r'#[0-9a-fA-F]{8}\b|#[0-9a-fA-F]{6}\b|#[0-9a-fA-F]{4}\b|#[0-9a-fA-F]{3}\b|(?<![\w-])(?:white|black)(?![\w-])')
KEEP_PROPERTIES = ('box-shadow', 'text-shadow')
HEADER = ('/* Generated by scripts/build_dark_theme.py from assets/styles.css. Do not edit. */\n'
          f'{SCOPE}{{color-scheme:dark}}\n')


def parse(css):
    """Split minified CSS into ('rule', selector, body) and ('at', prelude, children)."""
    blocks, i = [], 0
    while True:
        start = css.find('{', i)
        if start < 0:
            return blocks
        prelude = css[i:start].strip()
        if prelude.startswith('@'):
            depth, end = 1, start + 1
            while depth:
                depth += {'{': 1, '}': -1}.get(css[end], 0)
                end += 1
            blocks.append(('at', prelude, parse(css[start + 1:end - 1])))
            i = end
        else:
            end = css.index('}', start)
            blocks.append(('rule', prelude, css[start + 1:end]))
            i = end + 1


def dark(match):
    token = match.group(0)
    if token in ('white', 'black'):
        token = '#ffffff' if token == 'white' else '#000000'
    digits = token[1:]
    if len(digits) in (3, 4):
        digits = ''.join(c * 2 for c in digits)
    r, g, b = (int(digits[k:k + 2], 16) / 255 for k in (0, 2, 4))
    alpha = digits[6:8]
    h, l, s = colorsys.rgb_to_hls(r, g, b)
    lightness = 0.10 + (1 - l) * 0.82
    # Dark surfaces keep only a hint of their tint; lighter text and accents keep it all.
    r, g, b = colorsys.hls_to_rgb(h, lightness, s * 0.35 if lightness < 0.3 else s)
    return '#' + ''.join(f'{round(c * 255):02x}' for c in (r, g, b)) + alpha


def scope(selector):
    parts = []
    for part in selector.split(','):
        part = part.strip()
        if part == ':root':
            parts.append(SCOPE)
        elif part.startswith('html'):
            parts.append(SCOPE + part[4:])
        else:
            parts.append(f'{SCOPE} {part}')
    return ','.join(parts)


def emit(blocks):
    out = []
    for kind, prelude, content in blocks:
        if kind == 'at':
            inner = emit(content)
            if inner:
                out.append(f'{prelude}{{{inner}}}')
            continue
        if '::backdrop' in prelude:
            continue
        declarations = [d for d in content.split(';') if d.strip()]
        coloured = [d.split(':', 1)[0] + ':' + COLOR.sub(dark, d.split(':', 1)[1])
                    for d in declarations if ':' in d and COLOR.search(d.split(':', 1)[1])
                    and d.split(':', 1)[0].strip() not in KEEP_PROPERTIES]
        if coloured:
            out.append(f'{scope(prelude)}{{{";".join(coloured)}}}')
    return ''.join(out)


def build(root):
    return HEADER + emit(parse((root/'assets/styles.css').read_text(encoding='utf-8'))) + '\n'


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--root', type=Path, default=ROOT)
    args = ap.parse_args()
    root = args.root.resolve()
    (root/'assets/styles-dark.css').write_text(build(root), encoding='utf-8')
    print('Scritto assets/styles-dark.css')


if __name__ == '__main__':
    main()
