#!/usr/bin/env python3
"""Generate the local code list dictionary from the OGC examples in sources/.

Reads the gml:Dictionary files listed under codeListSamples in
config/sources.json (OGC CityGML 3.0 code list examples, OGC 21-006r2 Annex E)
and writes:

  codelists/codelists.default.js  initial state, regenerated on every run
  codelists/codelists.js          working copy edited by the interface; created
                                  only when missing, or replaced with --reset

Values are copied as published, including the placeholders ({example-1}, ...)
that the source provides for many lists. Nothing is fetched (see
scripts/fetch_sources.py).
"""
from __future__ import annotations
import argparse
import json
import re
from pathlib import Path
from urllib.parse import urlparse
from lxml import etree as ET

ROOT = Path(__file__).resolve().parents[1]
GML = '{http://www.opengis.net/gml/3.2}'
PLACEHOLDER = re.compile(r'^\{example-\d+\}$')
DEFAULT_HEADER = ('/* Generated by scripts/build_codelists.py from the OGC CityGML 3.0 code list examples. '
                  'Do not edit: this is the initial state used by the Reset button. */\n')
LOCAL_HEADER = ('/* Local code list dictionary, edited by the interface (Save) and restored by Reset. '
                'Values are not part of the CityGML standard. */\n')


def text(el):
    return ' '.join((el.text or '').split()) if el is not None else ''


def read_dictionary(path):
    root = ET.parse(str(path), ET.XMLParser(resolve_entities=False, no_network=True)).getroot()
    if root.tag != GML + 'Dictionary':
        raise ValueError(f'{path}: la radice non e gml:Dictionary.')
    meta = root.find(f'{GML}metaDataProperty')
    record = meta[0] if meta is not None and len(meta) else None
    metadata = {ET.QName(child).localname: text(child) for child in record} if record is not None else {}
    if record is not None:
        metadata['metadataNamespace'] = ET.QName(record).namespace
    identifier = root.find(f'{GML}identifier')
    values = []
    for definition in root.iter(f'{GML}Definition'):
        code = definition.find(f'{GML}identifier')
        values.append({'code': text(code), 'codeSpace': code.get('codeSpace') if code is not None else None,
                       'name': text(definition.find(f'{GML}name')),
                       'description': text(definition.find(f'{GML}description'))})
    return {'identifier': text(identifier), 'codeSpace': identifier.get('codeSpace') if identifier is not None else None,
            'description': text(root.find(f'{GML}description')), 'metadata': metadata, 'values': values,
            'placeholder': bool(values) and all(PLACEHOLDER.match(v['name']) for v in values)}


def build(root):
    config = json.loads((root/'config/sources.json').read_text(encoding='utf-8'))
    samples = config['codeListSamples']
    manifest = json.loads((root/'sources/manifest.json').read_text(encoding='utf-8'))
    records = {r['url']: r for r in manifest['files'] if r.get('role') == 'codelist-sample'}
    unavailable = {u['url'] for u in manifest.get('unavailable', [])}
    lists = {}
    for file_name in samples['files']:
        module, name = file_name.removesuffix('.xml').split('.', 1)
        url = samples['baseUrl'] + file_name
        entry = {'module': module, 'url': url}
        record = records.get(url)
        if record and (root/record['path']).exists():
            entry.update(path=record['path'], retrievedAt=record['retrievedAt'], sha256=record['sha256'],
                         **read_dictionary(root/record['path']))
        else:
            entry.update(unavailable=True, availableAtSource=url not in unavailable, values=[], placeholder=False)
        lists[name] = entry
    return {'format': 1,
            'source': {'title': 'OGC CityGML 3.0 code list examples', 'version': '3.0.0',
                       'reference': 'OGC 21-006r2, Annex E (informative)', 'baseUrl': samples['baseUrl'],
                       'host': urlparse(samples['baseUrl']).hostname,
                       'retrievedAt': max((r['retrievedAt'] for r in records.values()), default=None)},
            'codeLists': lists}


def serialize(variable, header, data):
    return header + f'window.{variable} = ' + json.dumps(data, indent=1, ensure_ascii=False) + ';\n'


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--root', type=Path, default=ROOT)
    ap.add_argument('--reset', action='store_true', help='Sostituisce anche codelists/codelists.js con lo stato iniziale.')
    args = ap.parse_args()
    root = args.root.resolve()
    data = build(root)
    folder = root/'codelists'
    folder.mkdir(exist_ok=True)
    (folder/'codelists.default.js').write_text(serialize('CITYGML_CODELISTS_DEFAULT', DEFAULT_HEADER, {**data, 'kind': 'default'}), encoding='utf-8')
    working = folder/'codelists.js'
    if args.reset or not working.exists():
        working.write_text(serialize('CITYGML_CODELISTS', LOCAL_HEADER, {**data, 'kind': 'local'}), encoding='utf-8')
        print('Scritto codelists/codelists.js (stato iniziale).')
    else:
        print('codelists/codelists.js esiste gia: non modificato (usa --reset per ripristinarlo).')
    lists = data['codeLists'].values()
    print(json.dumps({'codeLists': len(data['codeLists']),
                      'withValues': sum(1 for l in lists if l['values'] and not l['placeholder']),
                      'placeholderOnly': sum(1 for l in lists if l['placeholder']),
                      'unavailable': sum(1 for l in lists if l.get('unavailable')),
                      'values': sum(len(l['values']) for l in lists)}, indent=2))


if __name__ == '__main__':
    main()
